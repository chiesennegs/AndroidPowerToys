"""Generate documentation-only fallbacks from pinned, Apache-2.0 AOSP declarations.
Only literal string declarations with an immediately adjacent Javadoc are accepted.
No inference from a key's spelling, annotations, numeric value, or device presence.
"""
from pathlib import Path
import re, html, json, hashlib
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'third_party/aosp-settings/Settings.java.reference'
REV='94b4c163b7dfe5ce3607f7bb8456f9573f7de57d'
assert hashlib.sha256(SOURCE.read_bytes()).hexdigest()=="73ff89ec4deb252465b8e8993764301fef96004d141c1d8fde4d6cb4f97a42e2", "Unexpected AOSP reference revision"
s=SOURCE.read_text()
starts=[(m.start(),m.group(1).upper()) for m in re.finditer(r'^    public static final class (System|Secure|Global|Config)\b',s,re.M)]
entries={}
for (begin,table),(end,_) in zip(starts,starts[1:]):
 if table=='CONFIG':continue
 section=s[begin:end]
 for m in re.finditer(r'public\s+static\s+final\s+String\s+([A-Z][A-Z0-9_]*)\s*=\s*"([a-z][a-z0-9_]*)"\s*;',section):
  start=section.rfind('/**',0,m.start());stop=section.find('*/',start)
  if start<0 or stop>m.start():continue
  gap=re.sub(r'//[^\n]*','',section[stop+2:m.start()])
  if re.sub(r'@\w+(?:\([^)]*\))?','',gap,flags=re.S).strip():continue
  doc=re.sub(r'^\s*\* ?','',section[start+3:stop],flags=re.M)
  deprecated='@deprecated' in doc or '@Deprecated' in gap
  doc=re.split(r'(?m)^\s*@\w+',doc)[0]
  doc=re.sub(r'\{@(?:link|linkplain)\s+([^}]+)\}',lambda x:x[1].split(' ',1)[-1].replace('#','.'),doc)
  doc=re.sub(r'\{@(?:code|literal)\s+([^}]+)\}',r'\1',doc)
  doc=re.sub(r'<(?:p|br|li)\b[^>]*>',' ',doc,flags=re.I)
  doc=re.sub(r'<[^>]*>','',doc)
  doc=' '.join(html.unescape(doc).split())
  if len(doc)<12 or doc.startswith(('Constant for','@')):continue
  if len(doc)>1000:
   cut=doc.rfind('. ',0,980);doc=doc[:cut+1] if cut>150 else doc[:975]+'…'
  if deprecated:doc='Legacy/deprecated in Android 17. '+doc
  line=s.count('\n',0,begin+start)+1
  entries[(table,m[2])]=(doc,f'https://android.googlesource.com/platform/frameworks/base/+/{REV}/core/java/android/provider/Settings.java#{line}')
rows=sorted(entries.items())
def lit(x):return json.dumps(x,ensure_ascii=False).replace('$','\\$')
out=['// Generated by tools/generate_descriptions.py. Do not edit.\n// Documentation excerpts: Copyright The Android Open Source Project; Apache-2.0.\npackage dev.androidpowertoys.app\n', 'internal fun sourceDescriptions(): Map<Pair<Table,String>,Explanation> = buildMap {']
for n in range(0,len(rows),40):out.append(f'    sourcePart{n//40}(this)')
out.append('}')
for n in range(0,len(rows),40):
 out.append(f'private fun sourcePart{n//40}(target: MutableMap<Pair<Table,String>,Explanation>) {{')
 for (table,key),(doc,url) in rows[n:n+40]:out.append(f'    target[Table.{table} to {lit(key)}] = Explanation({lit(doc)}, "Edit effects have not been assessed for this key. Source documentation describes its intended meaning, but does not establish that a direct write is supported or safe on this Pixel.", {lit(url)}, Risk.UNKNOWN, documentationOnly=true)')
 out.append('}')
(ROOT/'app/src/main/java/dev/androidpowertoys/app/SourceDescriptions.kt').write_text('\n'.join(out)+'\n')
print('Generated',len(rows),'exact-key source descriptions; source SHA256',hashlib.sha256(SOURCE.read_bytes()).hexdigest())
